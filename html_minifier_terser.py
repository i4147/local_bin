def build_parser():
    """Build parser."""
    p = argparse.ArgumentParser(
        prog="html-minifier-terser",
        description="Minify HTML, CSS and JavaScript in HTML files.",
    )
    p.add_argument("-V", "--version", action="version", version=f"%(prog)s {__version__}")
    p.add_argument("files", nargs="*", help="input HTML files; stdin is used when omitted")
    p.add_argument("-o", "--output", help="output file (default: stdout)")
    p.add_argument("-c", "--config-file", help="JSON configuration file")
    p.add_argument("--input-dir", help="input directory")
    p.add_argument("--output-dir", help="output directory")
    p.add_argument("--file-ext", default="html", help="file extension to read, e.g. html")
    for flag, dest, action, meta in CLI_FLAGS:
        if action in ("store_true", "store_false"):
            p.add_argument(flag, dest=dest, action=action, default=None)
        else:
            p.add_argument(flag, dest=dest, action=action, metavar=meta)
    return p


def _config(path: Path):
    if not path:
        return {}
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise HTMLMinifierError("config file must contain a JSON object")
    return data


def _options(args: Any) -> Options:
    data = _config(args.config_file)
    for _, dest, action, _ in CLI_FLAGS:
        v = getattr(args, dest)
        if v is None:
            continue
        if dest in {
            "customAttrAssign",
            "customAttrCollapse",
            "customAttrSurround",
            "customEventAttributes",
            "ignoreCustomComments",
            "ignoreCustomFragments",
            "processScripts",
        }:
            data[dest] = v
        elif dest in {"minifyCSS", "minifyJS", "minifyURLs"}:
            data[dest] = _jsonish(v)
        elif dest == "maxLineLength":
            data[dest] = int(v)
        else:
            data[dest] = v
    try:
        return Options(**data)
    except TypeError as e:
        raise HTMLMinifierError(f"invalid option: {e}") from e


def _files(args: Any) -> list[Path]:
    if args.input_dir:
        root = Path(args.input_dir)
        return sorted(p for p in root.rglob(f"*.{args.file_ext.lstrip('.')}") if p.is_file())
    return [Path(x) for x in args.files]


def main(argv: list[str] | None = None) -> int:
    """Run the command-line interface."""
    p = build_parser()
    args = p.parse_args(argv)
    try:
        opts = _options(args)
        files = _files(args)
        if not files:
            result = minify_sync(sys.stdin.read(), opts)
            (atomic_write(Path(args.output), result, encoding="utf-8") if args.output else sys.stdout.write(result))
            return 0
        for src in files:
            result = minify_sync(src.read_text(encoding="utf-8"), opts)
            if args.output_dir:
                dst = Path(args.output_dir) / src.name
                dst.parent.mkdir(parents=True, exist_ok=True)
                atomic_write(dst, result, encoding="utf-8")
            elif args.output:
                atomic_write(Path(args.output), result, encoding="utf-8")
            else:
                sys.stdout.write(result)
        return 0
    except (OSError, json.JSONDecodeError, HTMLMinifierError) as e:
        print(f"html-minifier-terser: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
