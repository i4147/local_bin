TOKEN_RE = re.compile(
    r"<!--(?P<comment>.*?)-->|<(?P<cdata>!\[CDATA\[.*?\]\])>|<!(?P<declaration>[^>]*)>|</(?P<close>[a-zA-Z][^\s>/]*)\s*>|<(?P<open>[a-zA-Z][^\s>/]*)((?P<attrs>[^>]*?)(?P<self>/?)>)",
    re.DOTALL | re.IGNORECASE,
)
ATTR_RE = re.compile(r"""([^\s=/>"']+)(?:\s*=\s*("([^"]*)"|'([^']*)'|([^\s"'=<>`]+)))?""")


@dataclass
class Options:
    """Store caseSensitive, collapseBooleanAttributes, collapseInlineTagWhitespace, collapseWhitespace, conservativeCollapse and related state."""

    caseSensitive: bool = False
    collapseBooleanAttributes: bool = False
    collapseInlineTagWhitespace: bool = False
    collapseWhitespace: bool = False
    conservativeCollapse: bool = False
    continueOnParseError: bool = False
    customAttrAssign: list[str] | None = None
    customAttrCollapse: list[str] | None = None
    customAttrSurround: list[list[str]] | None = None
    customEventAttributes: list[str] | None = None
    decodeEntities: bool = False
    html5: bool = True
    ignoreCustomComments: list[str] | None = None
    ignoreCustomFragments: list[str] | None = None
    includeAutoGeneratedTags: bool = True
    keepClosingSlash: bool = False
    maxLineLength: int = 0
    minifyCSS: bool | dict[str, Any] = False
    minifyJS: bool | dict[str, Any] = False
    minifyURLs: bool | str | dict[str, Any] = False
    newlinesBeforeTagClose: bool = True
    preserveLineBreaks: bool = False
    preventAttributesEscaping: bool = False
    processConditionalComments: bool = False
    processScripts: list[str] | None = None
    quoteCharacter: str = '"'
    removeAttributeQuotes: bool = False
    removeComments: bool = False
    removeEmptyAttributes: bool = False
    removeEmptyElements: bool = False
    removeOptionalTags: bool = False
    removeRedundantAttributes: bool = False
    removeScriptTypeAttributes: bool = False
    removeStyleLinkTypeAttributes: bool = False
