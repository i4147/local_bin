def _patterns(values: list[Any] | None):
    out = []
    for v in values or []:
        out.append(
            re.compile(v[1:-1]) if v.startswith("/") and v.endswith("/") and len(v) > 1 else re.compile(re.escape(v))
        )
    return out


def _jsonish(v: str):
    v = v.strip()
    if not v or v.lower() == "true":
        return True
    if v.lower() == "false":
        return False
    try:
        return json.loads(v)
    except json.JSONDecodeError:
        return v


def _css(css: str, _) -> str:
    if not css.strip():
        return css
    return rcssmin.cssmin(css) if rcssmin else re.sub(r"\s+", " ", css).strip()


def _js(js: str, _) -> str:
    if not js.strip():
        return js
    return rjsmin.jsmin(js) if rjsmin else re.sub(r"\s+", " ", js).strip()


def _escape_attr(value: str, quote: str, prevent: Any) -> str:
    if prevent:
        return value
    value = value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return value.replace('"', "&quot;") if quote == '"' else value.replace("'", "&#39;")


def _unquotable(v: str) -> bool:
    return bool(v) and not re.search(r"""[\s"'=<>`&]""", v)


def _parse_attrs(text: str):
    attrs = []
    pos = 0
    while pos < len(text):
        m = ATTR_RE.search(text, pos)
        if not m:
            break
        name = m.group(1)
        if m.group(2) is None:
            attrs.append((name, None, None))
        elif m.group(3) is not None:
            attrs.append((name, m.group(3), '"'))
        elif m.group(4) is not None:
            attrs.append((name, m.group(4), "'"))
        else:
            attrs.append((name, m.group(5), None))
        pos = m.end()
    return attrs


class _Minifier:
    def __init__(self, o: Options) -> None:
        self.o = o
        self.ignore_comments = _patterns(o.ignoreCustomComments)
        self.fragments = _patterns(o.ignoreCustomFragments)

    def minify(self, html: str) -> str:
        placeholders = {}
        for i, p in enumerate(self.fragments):
            key = f"\x00F{i}\x00"

            def repl(m: re.Match[str], key: str = key) -> str:
                placeholders[key] = m.group(0)
                return key

            html = p.sub(repl, html)
        out = []
        pos = 0
        stack = []
        for m in TOKEN_RE.finditer(html):
            if m.start() < pos:
                continue
            out.append(self._text(html[pos : m.start()], bool(stack)))
            pos = m.end()
            if m.group("comment") is not None:
                out.append(self._comment(m.group(0), m.group("comment")))
            elif m.group("cdata") is not None:
                out.append(m.group(0))
            elif m.group("declaration") is not None:
                out.append(self._declaration(m.group(0)))
            elif m.group("close") is not None:
                name = m.group("close").lower()
                if stack and stack[-1] == name:
                    stack.pop()
                out.append(f"</{name}>")
            else:
                name = m.group("open").lower()
                out.append(self._tag(name, m.group("attrs") or "", m.group("self") == "/"))
                if name in {"pre", "script", "style", "textarea"} and m.group("self") != "/":
                    close = re.compile(rf"</{re.escape(name)}\s*>", re.IGNORECASE).search(html, pos)
                    if close:
                        out.append(html[pos : close.start()])
                        out.append(close.group(0))
                        pos = close.end()
                    else:
                        out.append(html[pos:])
                        pos = len(html)
                elif name not in VOID_ELEMENTS and m.group("self") != "/":
                    stack.append(name)
        out.append(self._text(html[pos:], bool(stack)))
        result = "".join(out)
        for k, v in placeholders.items():
            result = result.replace(k, v)
        return result

    def _text(self, t: str, in_el: Any) -> str:
        if not self.o.collapseWhitespace:
            return t
        if self.o.conservativeCollapse:
            return re.sub(r"\s+", " ", t)
        if self.o.preserveLineBreaks and "\n" in t:
            return re.sub(r"[ \t\r]*\n\s*", "\n", t).strip()
        return re.sub(r"\s+", " ", t).strip()

    def _comment(self, whole: Any, body: str) -> str:
        if self.o.removeComments and not any(p.search(body.lstrip()) for p in self.ignore_comments):
            return ""
        return whole

    def _declaration(self, w: Any) -> str:
        return "<!doctype html>" if self.o.useShortDoctype and re.match(r"<!doctype\s+html", w, re.IGNORECASE) else w

    def _tag(self, name: str, attrs_text: str, self_close: Any) -> str:
        rendered = []
        for raw, value, quote in _parse_attrs(attrs_text):
            a = raw if self.o.caseSensitive else raw.lower()
            if self.o.removeEmptyAttributes and value is not None and not value.strip():
                continue
            if value is not None:
                if (
                    name == "script"
                    and a == "type"
                    and self.o.removeScriptTypeAttributes
                    and value.lower()
                    in {
                        "text/javascript",
                        "text/ecmascript",
                        "text/jscript",
                        "application/javascript",
                        "application/x-javascript",
                        "application/ecmascript",
                    }
                ):
                    continue
                if (
                    name in {"style", "link"}
                    and a == "type"
                    and self.o.removeStyleLinkTypeAttributes
                    and value.lower() == "text/css"
                ):
                    continue
            if self.o.removeRedundantAttributes and value is not None:
                if REDUNDANT_ATTRS.get((name, a)) == value.lower():
                    continue
            if self.o.collapseBooleanAttributes and a in BOOLEAN_ATTRS:
                rendered.append(a)
                continue
            if value is None:
                rendered.append(a)
                continue
            if self.o.minifyCSS and name == "style" and a == "style":
                value = _css(value, self.o.minifyCSS)
            if self.o.minifyJS and a.startswith("on") and len(a) > 2:
                value = _js(value, self.o.minifyJS)
            if self.o.removeAttributeQuotes and quote and _unquotable(value):
                rendered.append(f"{a}={value}")
                continue
            q = self.o.quoteCharacter if quote else '"'
            rendered.append(f"{a}={q}{_escape_attr(value, q, self.o.preventAttributesEscaping)}{q}")
        if self.o.sortAttributes:
            rendered.sort()
        part = (" " + " ".join(rendered)) if rendered else ""
        if self.o.removeTagWhitespace:
            part = re.sub(r"\s+", " ", part)
        slash = "/" if self_close and (self.o.keepClosingSlash or name in VOID_ELEMENTS) else ""
        return f"<{name}{part}{slash}>"


async def minify(value: str, options: Options | dict[str, Any] | None = None) -> str:
    opts = options if isinstance(options, Options) else Options(**(options or {}))
    return _Minifier(opts).minify(value)


def minify_sync(value: str, options: Options | dict[str, Any] | None = None) -> str:
    """Minify sync."""
    opts = options if isinstance(options, Options) else Options(**(options or {}))
    return _Minifier(opts).minify(value)


